"""Generate src/common/grapheme_break_table.inc, the grapheme-cluster-break table used by subtitles.cpp.

Needs the ICU 74 runtime (libicuuc.so.74, Unicode 15.1); no headers are needed:

  python3 scripts/gen_grapheme_tables.py > src/common/grapheme_break_table.inc

Each row is (first, last, class): class is the Grapheme_Cluster_Break value (numbered below), with bit 0x80 set for
Extended_Pictographic. Rows cover every code point whose class is not Other or that is Extended_Pictographic;
adjacent code points with the same value are merged.
"""
import ctypes

u = ctypes.CDLL("libicuuc.so.74")
prop_enum = u.u_getPropertyEnum_74
prop_enum.argtypes = [ctypes.c_char_p]
prop_enum.restype = ctypes.c_int
value_enum = u.u_getPropertyValueEnum_74
value_enum.argtypes = [ctypes.c_int, ctypes.c_char_p]
value_enum.restype = ctypes.c_int
int_value = u.u_getIntPropertyValue_74
int_value.argtypes = [ctypes.c_int32, ctypes.c_int]
int_value.restype = ctypes.c_int32
version = (ctypes.c_uint8 * 4)()
u.u_getUnicodeVersion_74(version)

GCB = prop_enum(b"Grapheme_Cluster_Break")
EXTPICT = prop_enum(b"Extended_Pictographic")
# Our numbering (must match GraphemeBreak in subtitles.cpp).
NAMES = [
    "Other",
    "CR",
    "LF",
    "Control",
    "Extend",
    "ZWJ",
    "Regional_Indicator",
    "Prepend",
    "SpacingMark",
    "L",
    "V",
    "T",
    "LV",
    "LVT",
]
ICU_TO_OURS = {value_enum(GCB, name.encode()): index for index, name in enumerate(NAMES)}

rows = []
current = None
for cp in range(0x110000):
    cls = ICU_TO_OURS[int_value(cp, GCB)]
    value = cls | (0x80 if int_value(cp, EXTPICT) else 0)
    if value == 0:
        if current is not None:
            rows.append(current)
            current = None
        continue
    if current is not None and current[2] == value and current[1] == cp - 1:
        current = (current[0], cp, value)
    else:
        if current is not None:
            rows.append(current)
        current = (cp, cp, value)
if current is not None:
    rows.append(current)

print(
    f"// Generated by scripts/gen_grapheme_tables.py from ICU 74 (Unicode {'.'.join(map(str, version[:3]))}):"
    " Grapheme_Cluster_Break and Extended_Pictographic. Do not edit."
)
print(
    "// Unicode Character Database data: Copyright (c) 1991-2026 Unicode, Inc., Unicode License v3 "
    "(THIRD_PARTY_NOTICES.md)."
)
print(
    f"// {len(rows)} ranges: {{first, last, class | 0x80 if Extended_Pictographic}}; classes: "
    + ", ".join(f"{i}={n}" for i, n in enumerate(NAMES))
)
for first, last, value in rows:
    print(f"{{0x{first:X}, 0x{last:X}, {value}}},")
