"""Generate src/speechlm/pee/timestamp_unit_tables.inc, the Unicode tables of the SALM timestamp alignment units
(timestamp_alignment.cpp): NeMo's script detection (Unicode character name prefixes) and its lexical characters (general
category L*, M* or N*). NeMo applies NFC first; the aligner takes the decoder's text as it is.

Run with Python 3.13 (Unicode 15.1, as NeMo's documented environment):

  python3.13 scripts/gen_timestamp_unit_tables.py > src/speechlm/pee/timestamp_unit_tables.inc
"""
import sys
import unicodedata

CODE_POINTS = range(sys.maxunicode + 1)


def ranges(predicate):
    out = []
    for cp in CODE_POINTS:
        if predicate(cp):
            if out and out[-1][1] == cp - 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
    return out


def name_prefix(*prefixes):
    return lambda cp: unicodedata.name(chr(cp), "").startswith(prefixes)


def emit_ranges(name, comment, rows):
    print(f"// {comment}: {len(rows)} ranges {{first, last}}")
    print(f"constexpr CodePointRange {name}[] = {{")
    for a, b in rows:
        print(f"    {{0x{a:X}, 0x{b:X}}},")
    print("};")


print(
    f"// Generated by scripts/gen_timestamp_unit_tables.py from Unicode {unicodedata.unidata_version}. Do not edit."
)
print(
    "// Unicode Character Database data: Copyright (c) 1991-2026 Unicode, Inc., Unicode License v3 "
    "(THIRD_PARTY_NOTICES.md)."
)
emit_ranges(
    "kLexical",
    "general category L*, M* or N*",
    ranges(lambda cp: unicodedata.category(chr(cp))[0] in "LMN"),
)
emit_ranges(
    "kMark", "general category M*", ranges(lambda cp: unicodedata.category(chr(cp))[0] == "M")
)
emit_ranges("kHangul", "character names starting HANGUL", ranges(name_prefix("HANGUL")))
emit_ranges(
    "kKana",
    "character names starting HIRAGANA or KATAKANA",
    ranges(name_prefix("HIRAGANA", "KATAKANA")),
)
emit_ranges(
    "kHan",
    "character names starting CJK UNIFIED IDEOGRAPH or CJK COMPATIBILITY IDEOGRAPH",
    ranges(name_prefix("CJK UNIFIED IDEOGRAPH", "CJK COMPATIBILITY IDEOGRAPH")),
)
emit_ranges("kThai", "character names starting THAI", ranges(name_prefix("THAI")))
