"""Generate src/speechlm/letter_mark_table.inc: the code point ranges whose Unicode general category is a letter (L*)
or a mark (M*), used by the SALM script guard.

  python3 scripts/gen_letter_mark_table.py > src/speechlm/letter_mark_table.inc
"""
import sys
import unicodedata

ranges = []
for cp in range(sys.maxunicode + 1):
    if unicodedata.category(chr(cp))[0] in "LM":
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
print(
    f"// Generated by scripts/gen_letter_mark_table.py from Unicode {unicodedata.unidata_version}: "
    "code points of general category L* or M*. Do not edit."
)
print(
    "// Unicode Character Database data: Copyright (c) 1991-2026 Unicode, Inc., Unicode License v3 "
    "(THIRD_PARTY_NOTICES.md)."
)
print(f"// {len(ranges)} ranges: {{first, last}}")
for a, b in ranges:
    print(f"{{0x{a:X}, 0x{b:X}}},")
